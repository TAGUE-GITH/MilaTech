ALTER TABLE product ADD COLUMN image_id VARCHAR(36) REFERENCES image (id);

-- « order » est un mot reserve en SQL : la table s'appelle online_order
CREATE TABLE online_order (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- CMD-2026-00001, attribuee juste apres l'enregistrement
    reference     VARCHAR(20) UNIQUE,
    customer_id   BIGINT      NOT NULL REFERENCES customer (id),
    status        VARCHAR(20) NOT NULL CHECK (status IN ('EN_ATTENTE', 'CONFIRMEE', 'PRETE', 'REMISE', 'ANNULEE')),
    delivery_mode VARCHAR(20) NOT NULL CHECK (delivery_mode IN ('RETRAIT', 'LIVRAISON')),
    address       VARCHAR(255),
    phone         VARCHAR(30) NOT NULL,
    note          VARCHAR(500),
    -- Somme des lignes (positive une fois les lignes ajoutees), frais de livraison a part
    subtotal      BIGINT      NOT NULL CHECK (subtotal >= 0),
    delivery_fee  BIGINT      NOT NULL CHECK (delivery_fee >= 0),
    cancel_reason VARCHAR(255),
    -- Vente creee quand la commande est remise au client et payee
    sale_id       BIGINT UNIQUE REFERENCES sale (id),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_online_order_status ON online_order (status, created_at);
CREATE INDEX idx_online_order_customer ON online_order (customer_id);

-- Nom et prix figes au moment de la commande (comme pour les ventes, R4)
CREATE TABLE online_order_line (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT       NOT NULL REFERENCES online_order (id),
    product_id   BIGINT       NOT NULL REFERENCES product (id),
    product_name VARCHAR(160) NOT NULL,
    quantity     INTEGER      NOT NULL CHECK (quantity > 0),
    unit_price   BIGINT       NOT NULL CHECK (unit_price >= 0)
);

CREATE INDEX idx_online_order_line_order ON online_order_line (order_id);
