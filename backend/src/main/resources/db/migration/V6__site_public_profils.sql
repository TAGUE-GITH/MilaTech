-- Sprint 5 : site public, comptes clients, photos de profil et messages de contact

-- Images (photos de profil, puis photos des produits) stockees en base : le disque des hebergeurs
-- gratuits est efface a chaque redeploiement. Identifiant aleatoire : l'adresse ne peut pas etre devinee.
CREATE TABLE image (
    id           VARCHAR(36)     PRIMARY KEY,
    content_type VARCHAR(30)     NOT NULL,
    data         VARCHAR(400000) NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE app_user ADD COLUMN avatar_id VARCHAR(36) REFERENCES image (id);
-- Un compte client est relie a sa fiche client (ventes, reparations, formations)
ALTER TABLE app_user ADD COLUMN customer_id BIGINT UNIQUE REFERENCES customer (id);

CREATE TABLE contact_message (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(120)  NOT NULL,
    phone      VARCHAR(30)   NOT NULL,
    email      VARCHAR(160),
    subject    VARCHAR(160),
    message    VARCHAR(2000) NOT NULL,
    handled    BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
