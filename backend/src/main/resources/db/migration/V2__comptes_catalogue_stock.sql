-- Sprint 1 : comptes des employes, catalogue et mouvements de stock

CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(160) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    first_name    VARCHAR(80)  NOT NULL,
    last_name     VARCHAR(80)  NOT NULL,
    phone         VARCHAR(30),
    role          VARCHAR(20)  NOT NULL CHECK (role IN ('GERANT', 'VENDEUR', 'TECHNICIEN', 'FORMATEUR', 'CLIENT')),
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE category (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE supplier (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    VARCHAR(120) NOT NULL,
    phone   VARCHAR(30),
    email   VARCHAR(160),
    address VARCHAR(255)
);

CREATE TABLE product (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference       VARCHAR(40)  NOT NULL UNIQUE,
    name            VARCHAR(160) NOT NULL,
    category_id     BIGINT       NOT NULL REFERENCES category (id),
    supplier_id     BIGINT REFERENCES supplier (id),
    description     VARCHAR(2000),
    -- Francs CFA sans centimes (R11)
    purchase_price  BIGINT  NOT NULL DEFAULT 0 CHECK (purchase_price >= 0),
    sale_price      BIGINT  NOT NULL CHECK (sale_price > 0),
    -- R1 : la base refuse elle-meme un stock negatif
    quantity        INTEGER NOT NULL DEFAULT 0 CHECK (quantity >= 0),
    alert_threshold INTEGER NOT NULL DEFAULT 0 CHECK (alert_threshold >= 0),
    active          BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_product_category ON product (category_id);

-- R2 : chaque variation de stock est tracee
CREATE TABLE stock_movement (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id     BIGINT      NOT NULL REFERENCES product (id),
    type           VARCHAR(20) NOT NULL,
    quantity       INTEGER     NOT NULL CHECK (quantity <> 0),
    quantity_after INTEGER     NOT NULL CHECK (quantity_after >= 0),
    unit_cost      BIGINT,
    supplier_id    BIGINT REFERENCES supplier (id),
    reason         VARCHAR(255),
    author_id      BIGINT      NOT NULL REFERENCES app_user (id),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_movement_product ON stock_movement (product_id, created_at);
