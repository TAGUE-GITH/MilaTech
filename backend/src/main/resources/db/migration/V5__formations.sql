-- Sprint 4 : formations, inscriptions des apprenants et leurs paiements

CREATE TABLE training (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(120) NOT NULL,
    description VARCHAR(2000),
    start_date  DATE    NOT NULL,
    end_date    DATE    NOT NULL,
    fee         BIGINT  NOT NULL CHECK (fee >= 0),
    capacity    INTEGER NOT NULL CHECK (capacity >= 1),
    trainer_id  BIGINT REFERENCES app_user (id),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (end_date >= start_date)
);

CREATE TABLE enrollment (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- INS-2026-00001 (R10)
    reference   VARCHAR(20) UNIQUE,
    training_id BIGINT      NOT NULL REFERENCES training (id),
    customer_id BIGINT      NOT NULL REFERENCES customer (id),
    -- Prix convenu avec l'apprenant (remise possible)
    agreed_fee  BIGINT      NOT NULL CHECK (agreed_fee >= 0),
    status      VARCHAR(10) NOT NULL CHECK (status IN ('INSCRIT', 'TERMINE', 'ABANDON')),
    enrolled_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (training_id, customer_id)
);

-- Les paiements servent desormais aux reparations ET aux inscriptions : exactement l'un des deux
ALTER TABLE payment ADD COLUMN enrollment_id BIGINT REFERENCES enrollment (id);
ALTER TABLE payment ADD CONSTRAINT payment_one_target CHECK ((repair_id IS NULL) <> (enrollment_id IS NULL));
CREATE INDEX idx_payment_enrollment ON payment (enrollment_id);
