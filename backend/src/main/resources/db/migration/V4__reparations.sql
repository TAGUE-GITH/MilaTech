-- Sprint 3 : reparations, pieces utilisees, historique des etapes et paiements

CREATE TABLE repair (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- REP-2026-00001 (R10)
    reference      VARCHAR(20) UNIQUE,
    customer_id    BIGINT       NOT NULL REFERENCES customer (id),
    received_by    BIGINT       NOT NULL REFERENCES app_user (id),
    device_type    VARCHAR(20)  NOT NULL CHECK (device_type IN ('TELEPHONE', 'ORDINATEUR', 'TABLETTE', 'BLUETOOTH', 'AUTRE')),
    brand          VARCHAR(60),
    model          VARCHAR(80),
    serial_number  VARCHAR(60),
    accessories    VARCHAR(255),
    reception      VARCHAR(10)  NOT NULL CHECK (reception IN ('BOUTIQUE', 'DOMICILE')),
    reported_issue VARCHAR(1000) NOT NULL,
    diagnosis      VARCHAR(2000),
    status         VARCHAR(20)  NOT NULL,
    -- Main-d'oeuvre et estimation donnee au client, en FCFA
    labor_cost     BIGINT       NOT NULL DEFAULT 0 CHECK (labor_cost >= 0),
    estimated_cost BIGINT CHECK (estimated_cost >= 0),
    promised_on    DATE,
    received_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    returned_at    TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_repair_status ON repair (status);
CREATE INDEX idx_repair_customer ON repair (customer_id);

-- R4 et R7 : pieces prises dans le stock, prix figes
CREATE TABLE repair_part (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repair_id    BIGINT       NOT NULL REFERENCES repair (id),
    product_id   BIGINT       NOT NULL REFERENCES product (id),
    product_name VARCHAR(160) NOT NULL,
    quantity     INTEGER      NOT NULL CHECK (quantity > 0),
    unit_price   BIGINT       NOT NULL CHECK (unit_price >= 0),
    unit_cost    BIGINT       NOT NULL CHECK (unit_cost >= 0)
);

-- Historique : chaque etape, avec son auteur et une note facultative
CREATE TABLE repair_event (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repair_id  BIGINT      NOT NULL REFERENCES repair (id),
    status     VARCHAR(20) NOT NULL,
    note       VARCHAR(500),
    author_id  BIGINT      NOT NULL REFERENCES app_user (id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- R8 : acomptes et paiements (les paiements des formations s'y ajouteront au sprint 4)
CREATE TABLE payment (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repair_id   BIGINT REFERENCES repair (id),
    amount      BIGINT      NOT NULL CHECK (amount > 0),
    method      VARCHAR(20) NOT NULL CHECK (method IN ('ESPECES', 'MOBILE_MONEY')),
    received_by BIGINT      NOT NULL REFERENCES app_user (id),
    paid_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_payment_repair ON payment (repair_id);
