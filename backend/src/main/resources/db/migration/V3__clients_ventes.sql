-- Sprint 2 : clients et ventes

CREATE TABLE customer (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name  VARCHAR(120) NOT NULL,
    -- Chiffres seulement (espaces retires) pour retrouver un client par son numero
    phone      VARCHAR(30)  NOT NULL,
    email      VARCHAR(160),
    notes      VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_customer_phone ON customer (phone);

CREATE TABLE sale (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- VTE-2026-00001, attribuee juste apres l'enregistrement (R10)
    reference      VARCHAR(20) UNIQUE,
    customer_id    BIGINT REFERENCES customer (id),
    seller_id      BIGINT      NOT NULL REFERENCES app_user (id),
    payment_method VARCHAR(20) NOT NULL CHECK (payment_method IN ('ESPECES', 'MOBILE_MONEY')),
    -- Positif une fois les lignes ajoutees (la vente est enregistree avant ses lignes pour obtenir sa reference)
    total          BIGINT      NOT NULL CHECK (total >= 0),
    -- Marge theorique (R5) : somme de (prix de vente - prix d'achat) x quantite
    margin         BIGINT      NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_sale_created ON sale (created_at);

-- R4 : prix et nom figes au moment de la vente
CREATE TABLE sale_line (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id           BIGINT       NOT NULL REFERENCES sale (id),
    product_id        BIGINT       NOT NULL REFERENCES product (id),
    product_name      VARCHAR(160) NOT NULL,
    product_reference VARCHAR(40)  NOT NULL,
    quantity          INTEGER      NOT NULL CHECK (quantity > 0),
    unit_price        BIGINT       NOT NULL CHECK (unit_price >= 0),
    unit_cost         BIGINT       NOT NULL CHECK (unit_cost >= 0)
);

CREATE INDEX idx_sale_line_sale ON sale_line (sale_id);
