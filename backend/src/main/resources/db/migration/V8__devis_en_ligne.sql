-- Sprint 7 : demandes de devis de reparation envoyees depuis le site

CREATE TABLE quote_request (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- DEV-2026-00001, attribuee juste apres l'enregistrement
    reference     VARCHAR(20) UNIQUE,
    customer_id   BIGINT        NOT NULL REFERENCES customer (id),
    device_type   VARCHAR(20)   NOT NULL CHECK (device_type IN ('TELEPHONE', 'ORDINATEUR', 'TABLETTE', 'BLUETOOTH', 'AUTRE')),
    brand         VARCHAR(60),
    model         VARCHAR(80),
    issue         VARCHAR(1000) NOT NULL,
    -- Photo facultative de l'appareil ou de la panne
    image_id      VARCHAR(36) REFERENCES image (id),
    status        VARCHAR(20)   NOT NULL
        CHECK (status IN ('NOUVELLE', 'DEVIS_ENVOYE', 'ACCEPTEE', 'REFUSEE', 'ANNULEE', 'DEPOSEE')),
    -- Reponse de la boutique : prix estime en FCFA et explication
    quoted_price  BIGINT CHECK (quoted_price > 0),
    quote_message VARCHAR(500),
    quoted_by     BIGINT REFERENCES app_user (id),
    quoted_at     TIMESTAMP WITH TIME ZONE,
    -- Reponse du client (acceptation ou refus)
    answered_at   TIMESTAMP WITH TIME ZONE,
    -- Dossier de reparation ouvert quand le client apporte l'appareil
    repair_id     BIGINT UNIQUE REFERENCES repair (id),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_quote_status ON quote_request (status, created_at);
CREATE INDEX idx_quote_customer ON quote_request (customer_id);
